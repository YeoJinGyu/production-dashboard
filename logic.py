"""화면과 상관없이 일만 하는 코드 — tkinter를 전혀 모릅니다."""
import pandas as pd


def 파일읽기(경로):
    """엑셀을 읽어 DataFrame으로 돌려준다."""
    return pd.read_excel(경로, sheet_name=0)


def 집계하기(df, 기준열):
    """기준열로 묶어 건수·생산량·불량수·불량률을 구한다."""
    결과 = df.groupby(기준열).agg(
        건수=("생산량", "count"),
        생산량=("생산량", "sum"),
        불량수=("불량수", "sum"),
    ).reset_index()

    결과["불량률"] = (
        결과["불량수"] / 결과["생산량"] * 100
    ).round(2)

    return 결과


def 전체요약(df):
    """하단에 한 줄로 보여줄 요약 문장을 만든다."""
    생산 = df["생산량"].sum()
    불량 = df["불량수"].sum()

    return (
        f"총 생산 {생산:,}개 / "
        f"총 불량 {불량:,}개 / "
        f"전체 불량률 {불량/생산*100:.2f}%"
    )


def 저장하기(결과, 경로):
    """집계 결과를 엑셀 파일로 저장한다."""
    결과.to_excel(경로, index=False)
